import {chromium,expect} from '@playwright/test';
const browser=await chromium.launch({channel:process.env.WORKSHOP_BROWSER_CHANNEL||undefined,headless:true});
const page=await browser.newPage({viewport:{width:1512,height:1050}});
const origin=process.env.PREVIEW_URL||'http://localhost:3182';
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const button=name=>page.getByRole('button',{name,exact:true});
const url=sim=>`${origin}/journey/environment?${new URLSearchParams({experience:'project',task:'connections',pprofile:'dev',psim:JSON.stringify(sim)})}`;
await page.goto(url({}));await expect(page.locator('.dependency-survey')).toBeVisible();
await page.locator('.connection-practice').screenshot({path:'.verification/dependency-survey-overview.png',animations:'disabled'});
await button('Xem cấu hình Redis').click();
await expect(page.locator('.connection-pair [data-ready=true]').first()).toBeVisible();
await page.locator('.survey-detail').screenshot({path:'.verification/dependency-survey-comparison.png',animations:'disabled'});
await button('Ai sử dụng cấu hình này?').click();
await expect(page.locator('.survey-code [data-testid=highlighted-code]')).toHaveAttribute('data-ready','true');
await expect(page.locator('.survey-code [data-line="22"]')).toBeInViewport();
await page.locator('.survey-detail').screenshot({path:'.verification/dependency-survey-binding.png',animations:'disabled'});
await button('Lần đến nơi gọi / điều kiện').click();
await expect(page.locator('.survey-code [data-testid=highlighted-code]')).toHaveAttribute('data-ready','true');
await expect(page.locator('.survey-code [data-line="173"]')).toBeInViewport();
await page.locator('.survey-detail').screenshot({path:'.verification/dependency-survey-caller.png',animations:'disabled'});
await button('Xem kết luận và cần chuẩn bị gì').click();
await page.getByLabel('Nơi cung cấp dịch vụ',{exact:true}).selectOption('docker');
await page.locator('.survey-detail').screenshot({path:'.verification/dependency-survey-preparation.png',animations:'disabled'});
await page.goto(url({surveyGroup:'kafka',surveyStep:'binding',surveyGraph:true,surveyGoal:'event'}));
await expect(page.locator('.survey-code [data-testid=highlighted-code]')).toHaveAttribute('data-ready','true');
await expect(page.locator('.survey-usage-graph .react-flow__edge')).toHaveCount(2);
await page.locator('.survey-graph-disclosure').screenshot({path:'.verification/dependency-survey-graph.png',animations:'disabled'});
await page.setViewportSize({width:390,height:844});
await page.goto(url({surveyGroup:'redis',surveyStep:'binding'}));
await expect(page.locator('.survey-code [data-testid=highlighted-code]')).toHaveAttribute('data-ready','true');
await expect(page.locator('.survey-code [data-line="22"]')).toBeInViewport();
if(await page.evaluate(()=>document.documentElement.scrollWidth)>390)throw Error('Mobile overflow');
await page.screenshot({path:'.verification/dependency-survey-mobile.png',animations:'disabled'});
if(errors.length)throw Error(errors.join('\n'));
await browser.close();console.log('Captured overview, Java/Compose/container, binding, caller, preparation, optional graph and mobile.');
