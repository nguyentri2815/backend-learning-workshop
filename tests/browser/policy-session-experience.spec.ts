const base='/journey/policy?group=create&mode=session&sessionId=quote-beginner';
const at=(id:string)=>beginnerRounds.findIndex(r=>r.id===id);

test('snapshot differences distinguish per-round modifications from files created in the session',()=>{
 const delta=(before:number,after:number)=>sessionFileChanges(beginnerFiles,beginnerRows,before,after);
 expect(delta(at('controller-pattern')-1,at('controller-pattern'))).toEqual([]);
 expect(delta(-1,at('controller-pattern'))).toHaveLength(2);
 expect(delta(at('controller')-1,at('controller')).map(f=>[f.id,f.status])).toEqual([['controller','A']]);
 expect(delta(-1,at('controller'))).toHaveLength(3);
 expect(delta(at('wire')-1,at('wire')).map(f=>[f.id,f.status])).toEqual([['controller','M']]);
 expect(delta(-1,at('wire')).find(f=>f.id==='controller')?.status).toBe('A');
 for(const lanes of Object.values(beginnerFlows))for(const lane of lanes)for(const node of lane.nodes){
  if(node.ref){expect(node.from).toBeGreaterThan(0);expect(node.to).toBeLessThanOrEqual(beginnerSources[node.ref].rows.length);}
 }
 const read=beginnerFlows.survey.find(l=>l.label==='Xem cách đọc Quote theo ID')!;
 expect(read.nodes.map(n=>n.ref)).toEqual(['source-quoteController','source-quoteRead','source-quoteRepo']);
 expect(beginnerSources['source-quoteController'].rows[50].text).toContain('FindQuoteByIdFunc.class');
 expect(beginnerSources['source-quoteRead'].rows[35].text).toContain('quoteRepository.findById(quoteId)');
 expect(beginnerSources['source-quoteFunc'].rows[150].text).toContain('quoteAggregateRepository.save(command)');
});

