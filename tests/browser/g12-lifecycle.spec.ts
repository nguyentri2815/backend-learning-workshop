test("Compose command, project name and volume evidence match the read-only Java repo", {tag:"@source"},async()=>{
  for(const proof of [source.composeSetup.projectEvidence,source.composeSetup.dockerfile,source.composeSetup.legacyScript]){
    const raw=await readFile(`${source.composeSetup.directory}/${proof.path}`,"utf8");
    expect(createHash("sha256").update(raw).digest("hex")).toBe(proof.sourceSha256);
  }
  expect(source.composeSetup.projectName).toBe("sale-platform");
  expect(source.composeSetup.projectEvidence.rows.find(r=>r.line===102)?.text).toContain('projectName = "sale-platform"');
  expect(source.files.find(f=>f.id==="compose")?.rows.find(r=>r.line===82)?.text).toContain('./.docker/postgresql-write:/var/lib/postgresql/data');
});
